#include "libft.h"

void	ft_bzero(void *s, size_t n)
{
	size_t			i;
	char			*tmp_s;

	i = 0;
	tmp_s = (char *)s;
	while (i < n)
	{
		tmp_s[i] = '\0';
		i++;
	}
}
